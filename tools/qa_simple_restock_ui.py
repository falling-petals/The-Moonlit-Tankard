"""Shared stock controls: real hiring, paid purchase, policy editing and reload."""
from pathlib import Path
import json
from playwright.sync_api import sync_playwright

ROOT=Path(__file__).resolve().parents[1]
BASE='http://127.0.0.1:4173/'
KEY='moonlit-tankard-save-v1-debug'
report={'checks':[],'errors':[]}
def check(name,value):
    assert value,name
    report['checks'].append(name)
    print('PASS '+name,flush=True)

with sync_playwright() as p:
    browser=p.chromium.launch(channel='chrome',headless=True)
    page=browser.new_page(viewport={'width':1366,'height':768})
    page.on('pageerror',lambda e:report['errors'].append(str(e)))
    page.add_init_script("localStorage.setItem('moonlit-preferences',JSON.stringify({auto:false}));")
    page.goto(BASE+'?debug=1');page.wait_for_selector('#loading',state='detached')
    page.clock.install()
    raw=page.evaluate('''async()=>{const e=await import('./src/engine.js'),v=await import('./src/storage.js');const s=e.createGame();s.gold=10000;s.milestones=['cellar'];s.stock.ale=0;s.arrivalIn=1000;return v.publicSave(s);}''')
    page.goto(BASE+'assets/index.html');page.evaluate('([k,v])=>localStorage.setItem(k,v)',[KEY,raw])
    page.goto(BASE+'?debug=1');page.wait_for_selector('#loading',state='detached');page.clock.run_for(300)
    page.locator('.visit-bar [data-panel=stock]').click()
    check('manual restocking is available without any cellar employee',page.locator('[data-action=restock][data-drink=ale]').is_enabled())
    check('auto toggle explains missing employee and stays disabled',page.locator('[data-restock-auto]').is_disabled() and '雇佣补货伙伴' in page.locator('[data-restock-status]').inner_text())
    page.locator('[data-action=restock][data-drink=ale]').click();page.clock.run_for(400)
    check('manual purchase is instant and charges ingredient price',page.locator('[data-drink=ale]').first.locator('..').inner_text().find('库存 6 / 24')>=0 and page.locator('.modal-footer b.gold').inner_text()=='9964 G')
    page.locator('.restock-controls [data-panel=staff]').click()
    page.locator('[data-action=hire][data-staff=gemini]').click()
    page.locator('.modal-tabs [data-panel=stock]').click()
    check('hiring enables auto without additional setup',page.locator('[data-restock-auto]').is_enabled() and page.locator('[data-restock-auto]').is_checked())
    page.locator('.restock-settings summary').click()
    page.locator('[data-restock-low]').fill('7');page.locator('[data-restock-target]').fill('12');page.locator('[data-restock-budget]').fill('36')
    page.locator('[data-action=supply-save]').click()
    page.locator('.modal-close, .modal .close-button').first.click()
    page.locator('[data-action=business]').click();page.clock.run_for(600)
    page.locator('.visit-bar [data-panel=stock]').click()
    check('automatic paid stock arrives within the first second', '库存 12 / 24' in page.locator('[data-drink=ale]').first.locator('..').inner_text() and page.locator('.modal-footer b.gold').inner_text()=='9328 G')
    check('automatic purchases alone consume the daily budget', '36 / 36 G' in page.locator('[data-restock-spending]').inner_text())
    page.locator('.modal-tabs [data-panel=menu]').click()
    page.evaluate("window.menuMark=document.querySelector('#modal-root .modal')")
    page.clock.run_for(1200)
    check('restock cooldown does not remount the menu panel',page.evaluate("menuMark===document.querySelector('#modal-root .modal')"))
    page.locator('.modal-tabs [data-panel=stock]').click()
    page.locator('.restock-settings summary').click()
    page.locator('[data-restock-target]').fill('3');page.locator('[data-action=supply-save]').click()
    check('invalid targets are rejected without resetting the editor','无效补货设置' in page.locator('#toast').inner_text() and page.locator('[data-restock-target]').input_value()=='3')
    page.locator('[data-restock-target]').fill('12');page.locator('[data-restock-budget]').fill('321');page.locator('[data-restock-budget]').focus()
    page.clock.run_for(3000)
    check('live updates preserve unsaved values and input focus',page.locator('[data-restock-budget]').input_value()=='321' and page.locator('[data-restock-budget]').evaluate('e=>e===document.activeElement'))
    page.locator('[data-action=supply-save]').click()
    page.locator('[data-restock-auto]').uncheck()
    page.clock.run_for(2300)
    saved=page.evaluate('k=>JSON.parse(localStorage.getItem(k))',KEY)
    check('policy persists atomically across all drink rules',saved['cellar']['automation']['budget']==321 and all(r['low']==7 and r['target']==12 for r in saved['cellar']['automation']['rules'].values()))
    check('paid inventory has no production queues or casks',not saved['cellar']['casks'] and not saved['cellar']['production']['ready'] and saved['cellar']['production']['batch'] is None)
    page.locator('.modal-content').evaluate('e=>e.scrollTop=0')
    page.screenshot(path=str(ROOT/'screenshots/shared-restock-controls.png'))
    before=saved['gold'];page.reload();page.wait_for_selector('#loading',state='detached');page.clock.run_for(2500)
    page.locator('.visit-bar [data-panel=stock]').click()
    check('reload preserves off toggle and does not charge again',not page.locator('[data-restock-auto]').is_checked() and page.locator('.modal-footer b.gold').inner_text()==str(before)+' G')
    page.locator('.modal .close-button').click();page.locator('#cellar-button').click();page.clock.run_for(400)
    page.locator('[data-action=cellar-panel][data-panel=supply]').click()
    drawer=page.locator('[data-cellar-panel=supply]')
    drawer.locator('.restock-settings summary').click()
    page.locator('.cellar-scene-menu [data-panel=stock]').click()
    panel=page.locator('#modal-root .modal')
    panel.locator('.restock-settings summary').click()
    for key,value in [('budget','90'),('low','3'),('target','9')]:panel.locator('[data-restock-'+key+']').fill(value)
    panel.locator('[data-action=supply-save]').click();panel.locator('.close-button').click();page.clock.run_for(400)
    check('a mounted cellar editor synchronizes settings saved upstairs',drawer.locator('[data-restock-budget]').input_value()=='90' and drawer.locator('[data-restock-low]').input_value()=='3' and drawer.locator('[data-restock-target]').input_value()=='9')
    drawer.locator('[data-restock-budget]').fill('555')
    page.locator('.cellar-scene-menu [data-panel=stock]').click()
    panel.locator('.restock-settings summary').click();panel.locator('[data-restock-budget]').fill('777')
    panel.locator('[data-action=supply-save]').click();panel.locator('.close-button').click();page.clock.run_for(400)
    check('external policy updates preserve an unsaved cellar draft',drawer.locator('[data-restock-budget]').input_value()=='555' and '36 / 777 G' in drawer.locator('[data-restock-spending]').inner_text())
    check('normal progress remains untouched',page.evaluate('localStorage.getItem("moonlit-tankard-save-v1")') is None)
    check('no browser runtime errors',not report['errors'])
    browser.close()
(ROOT/'docs/qa-simple-restock-report.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
